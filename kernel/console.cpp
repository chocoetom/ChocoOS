uint32_t *s_addr = nullptr;
uint64_t s_w = 0, s_h = 0, s_pitch = 0;
uint32_t s_cx = 20, s_cy = 20;
constexpr uint32_t SCALE = 2; // Otimizado: 2× mais rápido que SCALE=1
uint64_t s_seq = 0;   // bumps on every visible change (the WM watches it)
bool s_chrome = true; // taskbar-style status only makes sense full-screen
char *s_cap = nullptr;      // shell output capture sink (nullptr = live console)
size_t s_cap_cap = 0, s_cap_len = 0;

inline void put_pixel(uint64_t x, uint64_t y, uint32_t c) {
    if (!s_addr || x >= s_w || y >= s_h) return;
    s_addr[y * s_pitch + x] = c;
}
void fill_rect(uint64_t x0, uint64_t y0, uint64_t w, uint64_t h, uint32_t c) {
    for (uint64_t y = y0; y < y0 + h && y < s_h; y++)
        for (uint64_t x = x0; x < x0 + w && x < s_w; x++)
            s_addr[y * s_pitch + x] = c;
}
void draw_char(char ch, uint64_t x, uint64_t y, uint32_t fg, uint32_t bg) {
    if (ch < 32 || ch > 126) ch = '?';
    const uint8_t *g = kFont[(size_t)(ch - 32)];
    for (int r = 0; r < 8; r++)
        for (int col = 0; col < 8; col++) {
            uint32_t c = ((g[r] >> (7 - col)) & 1) ? fg : bg;
            uint64_t px = x + (uint64_t)col * SCALE, py = y + (uint64_t)r * SCALE;
            put_pixel(px, py, c); put_pixel(px + 1, py, c);
            put_pixel(px, py + 1, c); put_pixel(px + 1, py + 1, c);
        }
}
void scroll(uint32_t bg) {
    // Otimização: memmove para cima ao invés de redesenhar tudo
    if (s_h >= s_cy + SCALE * 2 && s_pitch == s_w) {
        // Mover todas as linhas para cima 1 linha (usar util::memcpy)
        // Nota: s_pitch == s_w significa buffer contíguo (sem stride do hardware)
        for (uint64_t y = 0; y < s_h - SCALE; y++) {
            uint64_t dst_offset = y * s_pitch;
            uint64_t src_offset = (y + SCALE) * s_pitch;
            const char *src = (const char *)&s_addr[src_offset];
            char *dst = (char *)&s_addr[dst_offset];
            for (uint32_t i = 0; i < s_w * 4; i++) {
                dst[i] = src[i];
            }
        }
        // Limpar última linha
        for (uint64_t x = 0; x < s_w; x++) {
            s_addr[(s_h - SCALE) * s_pitch + x] = bg;
        }
    } else {
        // Fallback: fill tudo BG (Se pitch != width, não pode mover com memcpy)
        fill_rect(0, 0, s_w, s_h, bg);
    }
    s_cx = 20;
    s_cy = 20;
}

void emit_num(unsigned long long v, unsigned base, bool upper, uint32_t fg, uint32_t bg) {
    char buf[65]; const char *dig = upper ? "0123456789ABCDEF" : "0123456789abcdef";
    int i = 64; buf[i] = 0;
    if (v == 0) buf[--i] = '0';
    while (v && i > 0) { buf[--i] = dig[v % base]; v /= base; }
    print(&buf[i], fg, bg);
}

