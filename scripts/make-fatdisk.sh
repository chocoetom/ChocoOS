#!/usr/bin/env bash
# Builds build/fat.img: a small REAL FAT32 volume used as the /disk ramdisk.
# The kernel's FAT32 driver (kernel/proc/fat32.cpp) parses its BPB, walks the
# FAT cluster chains and reads 8.3 + LFN directory entries.
# Uses mtools (mformat/mmd/mcopy), installed by scripts/setup-windows.ps1.
# When mtools is missing the script skips cleanly: the kernel still builds and
# boots, just without the /disk volume.
set -e
cd "$(dirname "$0")/.."

IMG=build/fat.img
SIZE_MB=16
ROOT=build/fatroot

for t in mformat mmd mcopy; do
  if ! command -v "$t" >/dev/null 2>&1; then
    echo "[fatdisk] mtools ('$t') not found: skipping $IMG (kernel boots without /disk)"
    exit 0
  fi
done

echo "[fatdisk] staging sample tree..."
rm -rf "$ROOT" "$IMG"
mkdir -p "$ROOT/Documents/Archive" "$ROOT/System" "$ROOT/bin" "$ROOT/docs"

cat > "$ROOT/README.TXT" <<'EOF'
ChocoOS FAT32 ramdisk
---------------------
This is a real FAT32 volume, generated by mformat at build time.
The kernel FAT32 driver walks the FAT (cluster chains), parses 8.3 and long
file names (LFN) and mounts this volume at /disk.
EOF

cat > "$ROOT/hello world.txt" <<'EOF'
A long file name, with spaces: the LFN entries (attr 0x0F) carry this name.
EOF

cat > "$ROOT/Documents/notes.txt" <<'EOF'
Documents/notes.txt - a plain text file inside a subdirectory.
EOF

cat > "$ROOT/Documents/Todo List 2026.txt" <<'EOF'
- walk the FAT cluster chain
- parse long file names
- render in the File Explorer
EOF

cat > "$ROOT/Documents/Archive/old-notes.txt" <<'EOF'
Nested two levels deep: Documents/Archive/old-notes.txt
EOF

cat > "$ROOT/System/version.txt" <<'EOF'
ChocoOS FAT32 ramdisk, generated at build time by scripts/make-fatdisk.sh.
EOF

cat > "$ROOT/bin/README.txt" <<'EOF'
Placeholder directory, to exercise subdirectory navigation.
EOF

# Larger than one 512-byte cluster so the driver must follow a real chain.
for i in $(seq 1 80); do
  printf 'line %03d: the quick brown fox jumps over the lazy dog\n' "$i"
done > "$ROOT/docs/bigfile.txt"

echo "[fatdisk] formatting ${SIZE_MB} MiB FAT32 (-c 1 => 512 B clusters)..."
dd if=/dev/zero of="$IMG" bs=1M count="$SIZE_MB" status=none
mformat -F -i "$IMG" -v CHOCOOS -c 1 ::

echo "[fatdisk] copying sample tree..."
mcopy -i "$IMG" "$ROOT/README.TXT" "$ROOT/hello world.txt" ::/
mmd   -i "$IMG" ::/Documents ::/Documents/Archive ::/System ::/bin ::/docs
mcopy -i "$IMG" "$ROOT/Documents/notes.txt" "$ROOT/Documents/Todo List 2026.txt" ::/Documents/
mcopy -i "$IMG" "$ROOT/Documents/Archive/old-notes.txt" ::/Documents/Archive/
mcopy -i "$IMG" "$ROOT/System/version.txt" ::/System/
mcopy -i "$IMG" "$ROOT/bin/README.txt" ::/bin/
mcopy -i "$IMG" "$ROOT/docs/bigfile.txt" ::/docs/

echo "[fatdisk] $IMG ready ($(du -h "$IMG" | cut -f1))"
