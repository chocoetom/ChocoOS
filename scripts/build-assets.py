"""Convert icons/ assets into kernel headers (runs before CMake).

icons/*.png (except background*.*) -> kernel/gen/icons.inc (RGBA, alpha kept)
icons/background*.* -> kernel/gen/wallpaper.inc (640x400, background4.png first = boot default)

Icons are normalized to ICON_SIZE square: the sources come from the web at up
to 512x512, and build-assets embeds one 32-bit word per pixel as hex text, so
an unnormalized 512px icon would add ~3 MB to the kernel image per file.

Partial input is fine: each header is generated only when its sources
exist (otherwise the kernel uses fallbacks: text buttons, no taskbar
icons, procedural wallpaper). Always exits 0: assets never break the build.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS_DIR = os.path.join(ROOT, 'icons')
GEN = os.path.join(ROOT, 'kernel', 'gen')
ICONS_INC = os.path.join(GEN, 'icons.inc')
WALL_INC = os.path.join(GEN, 'wallpaper.inc')
WALL_W, WALL_H = 640, 400
ICON_SIZE = 24

# Icons the ring-3 UI blits directly (ring 3 cannot read kernel memory, so the
# same normalized bitmaps are emitted a second time for user programs).
UI_ICONS = [
    'folder-icon', 'documents', 'download-icon', 'txt-file', 'png-file',
    'python-file', 'cpp-file-icon', 'asm-file-icon', 'basic-file',
    'file-explorer', 'system-monitor', 'update-icon', 'computer',
    'code_icon', 'memory_icon', 'wifi_icon',
]
UI_HEADER = os.path.join(ROOT, 'user', 'lib', 'icons_ui.h')

# The web sources are pure-black line art with alpha (measured: every opaque
# pixel is #000000), which disappears on the dark ChocoOS theme. Icons whose
# opaque pixels are dark get re-tinted to these 0xRRGGBB values; alpha is kept
# so the antialiasing survives. Colourful icons are left untouched.
ICON_TINT = {
    'folder-icon':    0xF5A524,
    'documents':      0x7FB2E5,
    'download-icon':  0x7ED491,
    'txt-file':       0xEDE6F7,
    'png-file':       0xB7AEFF,
    'python-file':    0xF5C542,
    'cpp-file-icon':  0x8FB8E8,
    'asm-file-icon':  0xC9A0E8,
    'basic-file':     0x9A8BB5,
    'file-explorer':  0xF5A524,
    'system-monitor': 0xB7AEFF,
    'update-icon':    0xEDE6F7,
    'terminal-icon':  0xB7AEFF,
    'computer':       0x8FB8E8,
    # The monitor's navigation rail: each icon carries its tab's series colour,
    # so the rail and the charts speak the same language.
    'code_icon':      0x8B7BE8,
    'memory_icon':    0x4FB8D8,
    'wifi_icon':      0xF5A524,
}
DEFAULT_TINT = 0xEDE6F7
DARK_LUM = 60


def pascal(name):
    return ''.join(w.capitalize() for w in re.split(r'[^0-9A-Za-z]+', name) if w)


def tint_dark_icon(im, stem):
    """Replace near-black RGB with the theme colour, keeping alpha intact."""
    from PIL import Image
    raw = bytearray(im.tobytes())
    rs = gs = bs = n = 0
    for i in range(3, len(raw), 4):
        if raw[i] > 32:
            rs += raw[i - 3]; gs += raw[i - 2]; bs += raw[i - 1]; n += 1
    if not n:
        return im
    lum = 0.299 * rs / n + 0.587 * gs / n + 0.114 * bs / n
    if lum >= DARK_LUM:
        return im  # already coloured or light: leave it alone
    col = ICON_TINT.get(stem, DEFAULT_TINT)
    r, g, b = (col >> 16) & 0xFF, (col >> 8) & 0xFF, col & 0xFF
    for i in range(0, len(raw), 4):
        raw[i], raw[i + 1], raw[i + 2] = r, g, b
    return Image.frombytes('RGBA', im.size, bytes(raw))


def unique_tag(used, base):
    """download_icon.png and download-icon.png both pascalize to DownloadIcon;
    the lookup name stays the file stem, only the C identifier must differ."""
    tag, n = base, 2
    while tag in used:
        tag = '%s%d' % (base, n)
        n += 1
    used.add(tag)
    return tag


def load_icon(path):
    """RGBA bitmap normalized to (ICON_SIZE, ICON_SIZE), alpha preserved and
    dark line-art re-tinted for the dark theme."""
    from PIL import Image
    stem = os.path.splitext(os.path.basename(path))[0]
    im = Image.open(path).convert('RGBA')
    side = min(im.width, im.height)
    im = im.crop(((im.width - side) // 2, (im.height - side) // 2,
                  (im.width - side) // 2 + side, (im.height - side) // 2 + side))
    if im.size != (ICON_SIZE, ICON_SIZE):
        im = im.resize((ICON_SIZE, ICON_SIZE), Image.LANCZOS)
    return tint_dark_icon(im, stem)


def build_ui_icons(loaded):
    """Emit user/lib/icons_ui.h from the already normalized icon bitmaps."""
    picked = [(n, loaded[n]) for n in UI_ICONS if n in loaded]
    if not picked:
        print('[assets] no UI icons to emit')
        return
    used = set()
    names = []
    with open(UI_HEADER, 'w', newline='\n') as f:
        f.write('// generated by scripts/build-assets.py - do not edit\n')
        f.write('// icons/ normalized to %dx%d RGBA, for ring-3 programs.\n' % (ICON_SIZE, ICON_SIZE))
        f.write('#pragma once\n#include <stdint.h>\n\n')
        f.write('#define UIICON_SIZE %d\n\n' % ICON_SIZE)
        for stem, im in picked:
            tag = unique_tag(used, pascal(stem))
            raw = im.tobytes()
            f.write('static const uint8_t kUiIco%s[%d] = {\n' % (tag, len(raw)))
            for i in range(0, len(raw), 28):
                f.write('    ' + ','.join('0x%02x' % b for b in raw[i:i + 28]) + ',\n')
            f.write('};\n')
            names.append((stem, tag))
        f.write('\ntypedef struct UiIcon { const char *name; const uint8_t *rgba; } UiIcon;\n')
        f.write('static const UiIcon kUiIcons[] = {\n')
        for stem, tag in names:
            f.write('    { "%s", kUiIco%s },\n' % (stem, tag))
        f.write('};\n')
        f.write('static const int kUiIconCount = %d;\n' % len(names))
    print('[assets] %d UI icons -> user/lib/icons_ui.h' % len(picked))


def build_icons():
    # Wallpapers live in icons/ too but are NOT icons: background*.* files
    # would otherwise embed as giant RGBA bitmaps (background4.png did).
    paths = sorted(p for p in glob.glob(os.path.join(ICONS_DIR, '*.png'))
                   if not os.path.basename(p).startswith('background'))
    if not paths:
        if os.path.exists(ICONS_INC):
            os.remove(ICONS_INC)
        print('[assets] no icons -> text fallbacks')
        return 0
    try:
        from PIL import Image
    except ImportError:
        print('[assets] PIL missing, icons skipped (pip install pillow)')
        return 0
    os.makedirs(GEN, exist_ok=True)
    table = []
    loaded = {}
    used_tags = set()
    with open(ICONS_INC, 'w') as f:
        f.write('// generated by scripts/build-assets.py - do not edit\n')
        f.write('#pragma once\n')
        f.write('#define ASSET_ICONS 1\n')
        for path in paths:
            stem = os.path.splitext(os.path.basename(path))[0]
            tag = unique_tag(used_tags, pascal(stem))
            im = load_icon(path)
            w, h = im.width, im.height
            loaded[stem] = im
            raw = im.tobytes()
            px = [(raw[i], raw[i + 1], raw[i + 2], raw[i + 3])
                  for i in range(0, len(raw), 4)]
            f.write('static const unsigned kIcon%sW = %d, kIcon%sH = %d;\n' % (tag, w, tag, h))
            f.write('static const unsigned kIcon%s[%d] = {' % (tag, w * h))
            for i, (r, g, b, a) in enumerate(px):
                if i % 6 == 0:
                    f.write('\n')
                f.write('0x%02x%02x%02x%02x,' % (a, r, g, b))
            f.write('\n};\n')
            table.append((stem, tag, w, h))
        f.write('static const Asset kIconTable[] = {\n')
        for stem, tag, w, h in table:
            f.write('    { "%s", kIcon%s, %d, %d },\n' % (stem, tag, w, h))
        f.write('};\n')
        f.write('static const unsigned kIconTableCount = %d;\n' % len(table))
    print('[assets] %d icons' % len(table))
    build_ui_icons(loaded)
    return 0


def build_wallpapers():
    paths = []
    for pat in ('background*.jpg', 'background*.jpeg', 'background*.png', 'background*.bmp'):
        paths.extend(glob.glob(os.path.join(ICONS_DIR, pat)))
    paths = sorted(paths)
    # Default wallpaper first: background4.png is the ChocoOS identity
    # (purple/blue); the kernel boots with kWalls[0], so this file must
    # sort first regardless of what else lands in icons/.
    for i, p in enumerate(paths):
        if os.path.basename(p) == 'background4.png':
            paths.insert(0, paths.pop(i))
            break
    if not paths:
        if os.path.exists(WALL_INC):
            os.remove(WALL_INC)
        print('[assets] no backgrounds -> procedural wallpaper')
        return 0
    try:
        from PIL import Image
    except ImportError:
        print('[assets] PIL missing, wallpapers skipped (pip install pillow)')
        return 0
    os.makedirs(GEN, exist_ok=True)
    with open(WALL_INC, 'w') as f:
        f.write('// generated by scripts/build-assets.py - do not edit\n')
        f.write('#pragma once\n')
        f.write('#define ASSET_WALLPAPERS 1\n')
        f.write('static const unsigned kWallW = %d, kWallH = %d;\n' % (WALL_W, WALL_H))
        f.write('static const unsigned kWallCount = %d;\n' % len(paths))
        f.write('static const unsigned kWalls[%d][%d] = {\n' % (len(paths), WALL_W * WALL_H))
        for path in paths:
            im = Image.open(path).convert('RGB')
            scale = max(WALL_W / im.width, WALL_H / im.height)
            im = im.resize((int(im.width * scale + 0.5), int(im.height * scale + 0.5)), Image.LANCZOS)
            left = (im.width - WALL_W) // 2
            top = (im.height - WALL_H) // 2
            im = im.crop((left, top, left + WALL_W, top + WALL_H))
            f.write('  {')
            raw = im.tobytes()
            n = len(raw) // 3
            for i in range(n):
                if i % 8 == 0:
                    f.write('\n   ')
                r, g, b = raw[3 * i], raw[3 * i + 1], raw[3 * i + 2]
                f.write(' 0x%02x%02x%02x,' % (r, g, b))
            f.write('\n  },\n')
        f.write('};\n')
    print('[assets] %d wallpapers' % len(paths))
    return 0


if __name__ == '__main__':
    sys.exit(build_icons() or build_wallpapers())
