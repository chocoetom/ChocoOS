#!/usr/bin/env python3
"""Bake a proportional, anti-aliased UI font from a TTF into a C header.

The kernel and ring-3 programs are built with -mno-80387 -mno-sse, so runtime
TTF rasterization (stb_truetype/FreeType) is not an option yet -- that is
ROADMAP phase 25. Instead we rasterize here, once, with Pillow/FreeType and
emit an alpha-covered glyph table the UI blits with per-pixel blending.

Source font: Inter (SIL Open Font License 1.1) - assets/fonts/INTER-OFL.txt

Usage: python scripts/build-font.py [ttf] [pixel-size]
Output: user/lib/font_ui.h        (ring-3 apps)
        kernel/gen/uifont.inc     (window manager chrome: titles, labels, clock)
"""
import os
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    print('[assets] PIL missing, UI font skipped (pip install pillow)')
    sys.exit(0)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets", "fonts", "Inter.ttf")
SIZE = int(sys.argv[2]) if len(sys.argv) > 2 else 14
FIRST, LAST = 32, 126
OUT = os.path.join(ROOT, "user", "lib", "font_ui.h")
OUT_KERNEL = os.path.join(ROOT, "kernel", "gen", "uifont.inc")

if not os.path.exists(TTF):
    sys.exit(f"build-font: {TTF} not found (keep the previous font_ui.h)")

font = ImageFont.truetype(TTF, SIZE)
ascent, descent = font.getmetrics()
line = ascent + descent

glyphs = []
blob = bytearray()
for code in range(FIRST, LAST + 1):
    ch = chr(code)
    adv = max(1, int(round(font.getlength(ch))))
    pad = 3
    img = Image.new("L", (adv + pad * 2, line + pad * 2), 0)
    ImageDraw.Draw(img).text((pad, pad), ch, font=font, fill=255, anchor="la")
    box = img.getbbox()
    if box:
        x0, y0, x1, y1 = box
        crop = img.crop(box)
        off = len(blob)
        blob.extend(crop.tobytes())
        glyphs.append((x1 - x0, y1 - y0, adv, x0 - pad, y0 - pad, off))
    else:  # space and other empty glyphs
        glyphs.append((0, 0, adv, 0, 0, 0))

with open(OUT, "w", newline="\n") as f:
    f.write("// Generated by scripts/build-font.py - DO NOT EDIT.\n")
    f.write(f"// Source: {os.path.relpath(TTF, ROOT).replace(os.sep, '/')} at {SIZE}px,\n")
    f.write("//         proportional with alpha coverage (antialiasing).\n")
    f.write("// License: Inter - SIL Open Font License 1.1 (assets/fonts/INTER-OFL.txt).\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"#define UIFONT_FIRST {FIRST}\n")
    f.write(f"#define UIFONT_LAST  {LAST}\n")
    f.write(f"#define UIFONT_ASCENT  {ascent}\n")
    f.write(f"#define UIFONT_DESCENT {descent}\n")
    f.write(f"#define UIFONT_LINE    {line}\n")
    f.write(f"#define UIFONT_N       {LAST - FIRST + 1}\n\n")
    f.write("typedef struct UiGlyph {\n")
    f.write("    uint8_t w, h;        // alpha box size\n")
    f.write("    uint8_t adv;         // horizontal advance\n")
    f.write("    int8_t bx, by;       // alpha box offset from the pen\n")
    f.write("    uint16_t off;        // start in uifont_alpha\n")
    f.write("} UiGlyph;\n\n")
    f.write(f"static const uint8_t uifont_alpha[{len(blob)}] = {{\n")
    for i in range(0, len(blob), 24):
        f.write("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",\n")
    f.write("};\n\n")
    f.write(f"static const UiGlyph uifont_glyphs[UIFONT_N] = {{\n")
    for i, g in enumerate(glyphs):
        f.write(f"    {{{g[0]},{g[1]},{g[2]},{g[3]},{g[4]},{g[5]}}}, /* {chr(FIRST + i)!r} */\n")
    f.write("};\n")

# Kernel side: window manager chrome (titles, desktop labels, taskbar clock).
os.makedirs(os.path.dirname(OUT_KERNEL), exist_ok=True)
with open(OUT_KERNEL, "w", newline="\n") as f:
    f.write("// generated by scripts/build-font.py - do not edit\n")
    f.write(f"// Source: {os.path.relpath(TTF, ROOT).replace(os.sep, '/')} at {SIZE}px, "
            "proportional with alpha coverage.\n")
    f.write("// License: Inter - SIL Open Font License 1.1 (assets/fonts/INTER-OFL.txt).\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"#define UIFONT_ASCENT  {ascent}\n")
    f.write(f"#define UIFONT_DESCENT {descent}\n")
    f.write(f"#define UIFONT_LINE    {line}\n")
    f.write(f"#define UIFONT_FIRST   {FIRST}\n")
    f.write(f"#define UIFONT_LAST    {LAST}\n")
    f.write(f"#define UIFONT_N       {LAST - FIRST + 1}\n\n")
    f.write("struct UiFontGlyph {\n")
    f.write("    uint8_t w, h; uint8_t adv; int8_t bx, by; uint16_t off;\n")
    f.write("};\n\n")
    f.write(f"static const uint8_t kUiFontAlpha[{len(blob)}] = {{\n")
    for i in range(0, len(blob), 24):
        f.write("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",\n")
    f.write("};\n\n")
    f.write("static const UiFontGlyph kUiFontGlyphs[UIFONT_N] = {\n")
    for g in glyphs:
        f.write(f"    {{{g[0]},{g[1]},{g[2]},{g[3]},{g[4]},{g[5]}}},\n")
    f.write("};\n")

print(f"build-font: {os.path.relpath(OUT, ROOT).replace(os.sep, '/')} "
      f"+ {os.path.relpath(OUT_KERNEL, ROOT).replace(os.sep, '/')} "
      f"({len(glyphs)} glyphs, {len(blob)} B alpha, {SIZE}px, ascent {ascent}/descent {descent})")
